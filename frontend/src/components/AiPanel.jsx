import { useEffect, useRef, useState } from "react";
import { Link } from "react-router-dom";
import { Download, Send, Sparkles, Trash2 } from "lucide-react";
import api, { errorMessage } from "../api/client.js";
import { useI18n } from "../i18n/index.jsx";
import { useToast } from "../context/ToastContext.jsx";
import { cn } from "../lib/cn.js";
import { downloadWorkFile } from "../lib/downloadWork.js";
import { Modal } from "./ui/Modal.jsx";
import Button from "./ui/Button.jsx";
import Markdown from "./Markdown.jsx";
import { Alert, Spinner } from "./ui/feedback.jsx";
import { LogoMark } from "./visuals/Logo.jsx";

const QUICK = [
  { key: "ai.summarize", mode: "summary" },
  { key: "ai.explain", mode: "explain", text: "Explain this work in simple terms." },
  { key: "ai.keypoints", mode: "chat", text: "List the key points and the main results." },
  { key: "ai.code", mode: "code", text: "Write the code that implements the main idea of this work." },
  { key: "ai.quiz", mode: "quiz", text: "Quiz me on this work." },
];

/** Stacks AI: answers are grounded in this work's own files (RAG) and generated by Gemini on the server. */
export default function AiPanel({ open, onClose, content, signedIn }) {
  const { t } = useI18n();
  const toast = useToast();
  const [messages, setMessages] = useState([]);
  const [input, setInput] = useState("");
  const [busy, setBusy] = useState(false);
  const end = useRef(null);

  useEffect(() => { end.current?.scrollIntoView({ behavior: "smooth", block: "end" }); }, [messages, busy]);
  useEffect(() => { setMessages([]); }, [content?._id]);

  const push = (m) => setMessages((list) => [...list, m]);

  const ask = async (text, mode = "chat") => {
    const q = text.trim();
    if (!q || busy) return;
    push({ role: "user", text: q });
    setInput("");
    setBusy(true);
    try {
      const history = messages.filter((m) => !m.error).map((m) => ({ role: m.role, text: m.text }));
      const { data } = mode === "summary"
        ? await api.post("/api/ai/summary", { contentId: content._id }).then((r) => ({ data: { answer: r.data.summary, sources: [], usedFiles: true } }))
        : await api.post("/api/ai/chat", { contentId: content._id, message: q, mode, history });
      push({ role: "model", text: data.answer, sources: data.sources, usedFiles: data.usedFiles });
    } catch (err) {
      push({ role: "model", text: errorMessage(err, t), error: true });
    } finally { setBusy(false); }
  };

  const downloadFile = async (f, i) => {
    try { await downloadWorkFile(api, content._id, i, f.originalName); } catch (err) { toast.error(errorMessage(err, t)); }
  };

  return (
    <Modal open={open} onClose={onClose} size="lg" title={<span className="inline-flex items-center gap-2"><LogoMark className="size-6" />{t("ai.title")}</span>}
      footer={signedIn ? (
        <form onSubmit={(e) => { e.preventDefault(); ask(input); }} className="flex w-full items-end gap-2">
          <textarea value={input} onChange={(e) => setInput(e.target.value)} maxLength={1500} rows={1} placeholder={t("ai.placeholder")} aria-label={t("ai.placeholder")}
            onKeyDown={(e) => { if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); ask(input); } }}
            className="max-h-32 min-h-11 flex-1 resize-none rounded-2xl border border-line bg-raised px-4 py-2.5 text-ink placeholder:text-subtle focus:border-accent focus:outline-none focus:ring-2 focus:ring-accent/25" />
          <Button type="submit" size="icon" loading={busy} disabled={!input.trim()} aria-label={t("ai.send")}><Send className="size-4 rtl:rotate-180" /></Button>
        </form>
      ) : <p className="w-full text-center text-sm text-muted"><Link to="/login" className="text-accent-text underline">{t("nav.signin")}</Link> — {t("ai.signin")}</p>}>
      <div className="flex min-h-[50dvh] flex-col gap-4">
        {messages.length === 0 && (
          <div className="space-y-4">
            <p className="text-sm text-muted">{t("ai.sub")}</p>
            <div className="flex flex-wrap gap-2">
              {QUICK.map((q) => (
                <button key={q.key} disabled={!signedIn || busy} onClick={() => ask(q.text || t(q.key), q.mode)} className="inline-flex items-center gap-1.5 rounded-full border border-line bg-raised px-3.5 py-1.5 text-sm transition hover:border-accent hover:text-accent-text disabled:opacity-50">
                  <Sparkles className="size-3.5 text-accent-text" />{t(q.key)}
                </button>
              ))}
            </div>
            {content.files?.length > 0 && (
              <div>
                <p className="mb-2 text-xs font-medium uppercase tracking-wide text-muted">{t("ai.files")}</p>
                <div className="flex flex-wrap gap-2">
                  {content.files.map((f, i) => <button key={i} onClick={() => downloadFile(f, i)} className="inline-flex max-w-full items-center gap-1.5 rounded-full bg-surface px-3 py-1.5 text-xs transition hover:bg-line"><Download className="size-3.5 shrink-0" /><span className="truncate">{f.originalName}</span></button>)}
                </div>
              </div>
            )}
          </div>
        )}

        {messages.map((m, i) => (
          <div key={i} className={cn("flex", m.role === "user" ? "justify-end" : "justify-start")}>
            <div className={cn("max-w-[92%] min-w-0 rounded-2xl px-4 py-2.5 text-sm", m.role === "user" ? "bg-accent text-accent-ink" : m.error ? "border border-danger/30 bg-danger/10" : "border border-line bg-raised")}>
              {m.role === "user" ? <p className="whitespace-pre-wrap break-words">{m.text}</p> : m.error ? <p>{m.text}</p> : <Markdown text={m.text} />}
              {m.sources?.length > 0 && (
                <details className="mt-2 text-xs text-muted">
                  <summary className="cursor-pointer">{t("ai.sources")} ({m.sources.length})</summary>
                  <ul className="mt-1 space-y-1">{m.sources.map((s, j) => <li key={j} className="break-words"><span className="font-medium">{s.file}:</span> “{s.snippet}…”</li>)}</ul>
                </details>
              )}
              {m.role === "model" && !m.error && m.usedFiles === false && <p className="mt-2 text-xs text-muted">{t("ai.noFileText")}</p>}
            </div>
          </div>
        ))}
        {busy && <div className="flex items-center gap-2 text-sm text-muted"><Spinner className="size-4" />{t("ai.thinking")}</div>}
        <div ref={end} />
        {messages.length > 0 && <button onClick={() => setMessages([])} className="mx-auto inline-flex items-center gap-1.5 text-xs text-muted hover:text-ink"><Trash2 className="size-3.5" />{t("ai.clear")}</button>}
        <Alert tone="info" className="text-xs">{t("ai.disclaimer")}</Alert>
      </div>
    </Modal>
  );
}
